class RegisterActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        setContent {
            Mapa_testeTheme {
                Surface(
                    modifier = Modifier.fillMaxSize(),
                    color = MaterialTheme.colorScheme.background
                ) {
                    RegisterScreen(
                        onRegisterSuccess = { name, email, password, logradouro, number, bairro, complement, cep, city, state ->
                            try {
                                CarameloRepository.saveUserProfile(
                                    context = this,
                                    name = name,
                                    email = email,
                                    logradouro = logradouro,
                                    number = number,
                                    bairro = bairro,
                                    complement = complement,
                                    cep = cep,
                                    city = city,
                                    state = state
                                )

                                Toast.makeText(this, "Cadastro salvo localmente com sucesso!", Toast.LENGTH_SHORT).show()
                                val intent = Intent(this, VehicleRegisterActivity::class.java)
                                startActivity(intent)
                                finish()
                            } catch (e: Exception) {
                                Toast.makeText(this, "Erro ao salvar dados localmente: ${e.localizedMessage}", Toast.LENGTH_LONG).show()
                            }
                        },
                        onGoogleRegister = {
                            Toast.makeText(this, "Registro com Google realizado com sucesso!", Toast.LENGTH_SHORT).show()
                            val intent = Intent(this, VehicleRegisterActivity::class.java)
                            startActivity(intent)
                            finish()
                        },
                        onBackToLogin = {
                            finish()
                        },
                        onShowError = { message ->
                            Toast.makeText(this, message, Toast.LENGTH_SHORT).show()
                        }
                    )
                }
            }
        }
    }
}

